#!/usr/bin/env python3
"""Build and check an AP2 PaymentMandate that carries a Nano (XNO) settlement. Stdlib only, no key, no network.

AP2's PaymentMandate (ap2/models/mandate.py) is {payment_mandate_contents, user_authorization}.
The contents hold a PaymentResponse whose `details` is "a dictionary generated by a payment method":
here the x402 `exact` payload on network nano:mainnet, naming the send block the buyer published.

This tool never signs and never sends. The block hash is supplied by the buyer (made with nano-pay402);
without --block-hash the mandate is built as an UNPAID DRAFT (settlement.state = "unpaid") that a merchant
must refuse. `user_authorization` is left null: AP2 expects an SD-JWT from the user's own credential
provider, which this tool does not forge.

  python3 ap2_nano_mandate.py --merchant superpa.ge --pay-to nano_... --raw 100000000000000000000000000 \
      --request-id R1 [--block-hash 64HEX] [--cart-mandate-id C1]
  python3 ap2_nano_mandate.py --check mandate.json     # structural check against the AP2 model, exit 1 on a problem
"""
import argparse, hashlib, json, re, sys, uuid
from datetime import datetime, timezone

XNO = 10 ** 30
A = "13456789abcdefghijkmnopqrstuwxyz"
X402_METHOD = "https://www.x402.org/"


def valid_nano(addr):
    if not isinstance(addr, str) or not addr.startswith(("nano_", "xrb_")): return False
    body = addr.split("_", 1)[1]
    if len(body) != 60 or any(c not in A for c in body): return False
    n = 0
    for c in body[:52]: n = n * 32 + A.index(c)
    key = (n & ((1 << 256) - 1)).to_bytes(32, "big")
    chk = hashlib.blake2b(key, digest_size=5).digest()[::-1]
    m = 0
    for c in body[52:]: m = m * 32 + A.index(c)
    return m.to_bytes(5, "big") == chk


def build(merchant, pay_to, raw, request_id, block_hash=None, cart_mandate_id=None, label="Order", now=None):
    if not valid_nano(pay_to): raise ValueError("bad Nano address checksum")
    if not (isinstance(raw, int) and raw > 0): raise ValueError("raw must be a positive integer")
    if block_hash is not None and not re.fullmatch(r"[0-9A-Fa-f]{64}", block_hash): raise ValueError("block hash must be 64 hex")
    accept = {"x402Version": 2, "scheme": "exact", "network": "nano:mainnet", "asset": "XNO",
              "payTo": pay_to, "amount": str(raw), "settlement": "block_hash"}
    paid = block_hash is not None
    details = {"accepted": accept,
               "payload": {"block_hash": block_hash.upper()} if paid else {},
               "settlement": {"state": "paid" if paid else "unpaid", "verify": "re-read the block by hash from any public node; check link==payTo-account and amount==raw"}}
    if cart_mandate_id: details["cart_mandate_id"] = cart_mandate_id
    # AP2 PaymentCurrencyAmount.value is a float: it is the DISPLAY amount only. The exact amount is the integer raw string above.
    display = raw / XNO
    ts = (now or datetime.now(timezone.utc)).isoformat()
    return {"payment_mandate_contents": {
        "payment_mandate_id": "pm-" + uuid.uuid4().hex[:12],
        "payment_details_id": request_id,
        "payment_details_total": {"label": label, "amount": {"currency": "XNO", "value": display}, "refund_period": 30},
        "payment_response": {"request_id": request_id, "method_name": X402_METHOD, "details": details},
        "merchant_agent": merchant, "timestamp": ts},
        "user_authorization": None}


def check(m):
    """Return a list of problems; [] means it matches AP2's PaymentMandate model and the Nano rules."""
    p = []
    def need(d, k, t, path):
        if not isinstance(d, dict) or k not in d: p.append(f"{path}.{k} missing"); return None
        if not isinstance(d[k], t): p.append(f"{path}.{k} wrong type"); return None
        return d[k]
    c = need(m, "payment_mandate_contents", dict, "$")
    if c is None: return p
    for k in ("payment_mandate_id", "payment_details_id", "merchant_agent", "timestamp"): need(c, k, str, "contents")
    tot = need(c, "payment_details_total", dict, "contents")
    if tot:
        need(tot, "label", str, "total"); amt = need(tot, "amount", dict, "total")
        if amt: need(amt, "currency", str, "total.amount"); need(amt, "value", (int, float), "total.amount")
    r = need(c, "payment_response", dict, "contents")
    if r:
        need(r, "request_id", str, "response"); need(r, "method_name", str, "response")
        d = r.get("details")
        if not isinstance(d, dict): p.append("response.details missing"); return p
        a = d.get("accepted", {})
        if a.get("network") != "nano:mainnet": p.append("accepted.network must be nano:mainnet")
        if not valid_nano(a.get("payTo")): p.append("accepted.payTo not a valid Nano address")
        if not str(a.get("amount", "")).isdigit() or int(a["amount"]) <= 0: p.append("accepted.amount must be integer raw")
        h = d.get("payload", {}).get("block_hash")
        if d.get("settlement", {}).get("state") == "paid":
            if not (isinstance(h, str) and re.fullmatch(r"[0-9A-F]{64}", h)): p.append("paid mandate needs a 64-hex block_hash")
        elif h: p.append("unpaid mandate must not carry a block_hash")
    if m.get("user_authorization") not in (None,) and not isinstance(m["user_authorization"], str): p.append("user_authorization must be a string or null")
    return p


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--merchant"); ap.add_argument("--pay-to"); ap.add_argument("--raw", type=int)
    ap.add_argument("--request-id", default="request-1"); ap.add_argument("--block-hash"); ap.add_argument("--cart-mandate-id")
    ap.add_argument("--check")
    a = ap.parse_args(argv)
    if a.check:
        probs = check(json.load(open(a.check)))
        print("\n".join(probs) if probs else "OK: matches AP2 PaymentMandate shape and Nano rules"); return 1 if probs else 0
    if not (a.merchant and a.pay_to and a.raw): ap.error("--merchant --pay-to --raw required")
    m = build(a.merchant, a.pay_to, a.raw, a.request_id, a.block_hash, a.cart_mandate_id)
    probs = check(m)
    print(json.dumps(m, indent=1))
    if probs: print("\n".join(probs), file=sys.stderr); return 1
    print("OK: " + ("paid" if a.block_hash else "UNPAID DRAFT (a merchant must refuse until a block hash is added)"), file=sys.stderr); return 0


if __name__ == "__main__":
    sys.exit(main())
